def sync_single_symlink(target: Path, source: Path, verbose: bool = False) -> bool:
    """Ensure target is a symlink pointing to relative path of source."""
    rel_target = os.path.relpath(source, target.parent)
    if target.is_symlink():
        try:
            if os.readlink(target) == rel_target and target.exists():
                return True
        except OSError:
            pass
        target.unlink(missing_ok=True)
    elif target.exists() or os.path.lexists(target) or os.path.islink(target):
        remove_path(target)

    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() or os.path.lexists(target) or target.is_symlink():
        remove_path(target)
    is_dir = source.is_dir()
    os.symlink(rel_target, target, target_is_directory=is_dir)
    if verbose:
        print(f"  symlink: {target.relative_to(REPO)} -> {rel_target}")
    return True


def sync_single_copy_file(target: Path, source: Path, verbose: bool = False) -> bool:
    """Ensure target is a read-only copy of source."""
    if target.is_symlink():
        target.unlink(missing_ok=True)
    elif target.exists():
        if filecmp.cmp(source, target, shallow=False):
            make_readonly(target)
            return True
        make_writable(target)

    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    make_readonly(target)
    if verbose:
        print(f"  copy file: {target.relative_to(REPO)}")
    return True


def sync_dir_copy(target_dir: Path, source_dir: Path, clean: bool = False, verbose: bool = False) -> bool:
    """Ensure target_dir contains read-only copies of source_dir."""
    if target_dir.is_symlink():
        target_dir.unlink(missing_ok=True)
    target_dir.mkdir(parents=True, exist_ok=True)

    source_files: set[Path] = set()
    for root, _, files in os.walk(source_dir):
        rel_root = Path(root).relative_to(source_dir)
        dest_root = target_dir / rel_root
        dest_root.mkdir(parents=True, exist_ok=True)
        for f in files:
            src_file = Path(root) / f
            dest_file = dest_root / f
            source_files.add(dest_file.resolve())
            sync_single_copy_file(dest_file, src_file, verbose=verbose)

    if clean:
        for root, _, files in os.walk(target_dir):
            for f in files:
                dest_file = Path(root) / f
                if dest_file.name == "DO_NOT_EDIT.md":
                    continue
                if dest_file.resolve() not in source_files:
                    make_writable(dest_file)
                    dest_file.unlink(missing_ok=True)
                    if verbose:
                        print(f"  pruned orphan: {dest_file.relative_to(REPO)}")

    return True


# ── Full Sync Engine ──────────────────────────────────────────────────────────

def run_sync(mode: str, clean: bool = False, verbose: bool = False) -> int:
    """Execute framework synchronization under specified mode."""
    print(f"Synchronizing AI Framework toolchains and mirrors (mode: {mode.upper()})...")

    # 1. Directory mirrors
    for target_rel, source_rel in DIR_MAPPINGS.items():
        target = REPO / target_rel
        source = REPO / source_rel
        if not source.exists():
            print(f"Warning: source '{source_rel}' does not exist, skipping.", file=sys.stderr)
            continue
        if mode == "symlink":
            sync_single_symlink(target, source, verbose=verbose)
        else:
            sync_dir_copy(target, source, clean=clean, verbose=verbose)

    # 2. Single-file mirrors (ROUTING.md)
    for target_rel, source_rel in FILE_MAPPINGS.items():
        target = REPO / target_rel
        source = REPO / source_rel
        if not source.exists():
            print(f"Warning: source '{source_rel}' does not exist, skipping.", file=sys.stderr)
            continue
        if mode == "symlink":
            sync_single_symlink(target, source, verbose=verbose)
        else:
            sync_single_copy_file(target, source, verbose=verbose)

    # 3. Gemini mirrors (.gemini/agents/ and .gemini/skills/)
    gemini_agents_dir = REPO / ".gemini" / "agents"
    gemini_skills_dir = REPO / ".gemini" / "skills"
    gemini_agents_dir.mkdir(parents=True, exist_ok=True)
    gemini_skills_dir.mkdir(parents=True, exist_ok=True)

    # Per-file agents
    for agent_src in sorted((AI / "agents").glob("*.md")):
        agent_dst = gemini_agents_dir / agent_src.name
        if mode == "symlink":
            sync_single_symlink(agent_dst, agent_src, verbose=verbose)
        else:
            sync_single_copy_file(agent_dst, agent_src, verbose=verbose)

    # Per-item skills
    for skill_src in sorted(p for p in (AI / "skills").iterdir() if p.is_dir()):
        skill_dst = gemini_skills_dir / skill_src.name
        if mode == "symlink":
            sync_single_symlink(skill_dst, skill_src, verbose=verbose)
        else:
            sync_dir_copy(skill_dst, skill_src, clean=clean, verbose=verbose)

    # 4. In copy mode, inject DO_NOT_EDIT.md banners; in symlink mode remove if present
    for parent_dir in (REPO / ".claude", REPO / ".agents", REPO / ".gemini"):
        banner_path = parent_dir / "DO_NOT_EDIT.md"
        if mode == "copy":
            if parent_dir.is_dir():
                if banner_path.is_symlink():
                    banner_path.unlink(missing_ok=True)
                else:
                    make_writable(banner_path)
                banner_path.write_text(DO_NOT_EDIT_BANNER, encoding="utf-8")
                make_readonly(banner_path)
        else:
            remove_path(banner_path)

    # 5. Multi-toolchain generation (Cursor, Windsurf, Copilot, Gemini settings)
    targets = build_all_toolchains()
    for rel_path, expected_content in targets.items():
        full_path = REPO / rel_path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        if full_path.exists():
            make_writable(full_path)
        full_path.write_text(expected_content, encoding="utf-8")
        if verbose:
            print(f"  generated: {rel_path}")

    # 6. Record .sync_mode metadata
    manifest = {
        "version": 1,
        "mode": mode,
        "synced_at": datetime.now(timezone.utc).isoformat(),
        "generator": "ai/skills/sync-framework/scripts/sync_framework.py",
        "trees": {
            **DIR_MAPPINGS,
            **FILE_MAPPINGS,
            ".gemini/agents": "ai/agents",
            ".gemini/skills": "ai/skills",
        },
    }
    SYNC_MODE_FILE.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"Synchronized {len(targets)} toolchain files across Cursor, Windsurf, Copilot, and Gemini.")
    print(f"Framework mirrors synchronized: mode={mode} (.sync_mode updated).")
    return 0


# ── Check Routine ─────────────────────────────────────────────────────────────

def run_check(expected_mode: str | None = None, verbose: bool = False) -> int:
    """Verify that current framework trees and toolchains match expected sync state."""
    mode = expected_mode or get_current_sync_mode()
    drift: list[str] = []

    # 1. Check toolchain files
    targets = build_all_toolchains()
    for rel_path, expected_content in targets.items():
        full_path = REPO / rel_path
        if not full_path.exists():
            drift.append(f"{rel_path}: toolchain file missing")
        elif full_path.read_text(encoding="utf-8") != expected_content:
            drift.append(f"{rel_path}: content drift detected against canonical source")
        elif verbose:
            print(f"OK: {rel_path} in sync")

    # 2. Check directory mappings
    for target_rel, source_rel in DIR_MAPPINGS.items():
        target = REPO / target_rel
        source = REPO / source_rel
        if not target.exists() and not target.is_symlink():
            drift.append(f"{target_rel}: missing")
            continue
        if mode == "symlink":
            if not target.is_symlink():
                drift.append(f"{target_rel}: expected symlink, found real directory")
            elif not target.exists():
                drift.append(f"{target_rel}: broken symlink")
        else:
            if target.is_symlink():
                drift.append(f"{target_rel}: expected copy directory, found symlink")
            else:
                for root, _, files in os.walk(source):
                    rel = Path(root).relative_to(source)
                    for f in files:
                        t_file = target / rel / f
                        s_file = Path(root) / f
                        if not t_file.exists():
                            drift.append(f"{target_rel}/{rel}/{f}: missing copy file")
                        elif not filecmp.cmp(s_file, t_file, shallow=False):
                            drift.append(f"{target_rel}/{rel}/{f}: content mismatch with ai/")

    # 3. Check single-file mappings (ROUTING.md)
    for target_rel, source_rel in FILE_MAPPINGS.items():
        target = REPO / target_rel
        source = REPO / source_rel
        if not target.exists() and not target.is_symlink():
            drift.append(f"{target_rel}: missing")
            continue
        if mode == "symlink":
            if not target.is_symlink():
                drift.append(f"{target_rel}: expected symlink, found real file")
        else:
            if target.is_symlink():
                drift.append(f"{target_rel}: expected copy file, found symlink")
            elif not filecmp.cmp(source, target, shallow=False):
                drift.append(f"{target_rel}: content mismatch with {source_rel}")

    # 4. Check Gemini mirrors
    gemini_agents = REPO / ".gemini" / "agents"
    gemini_skills = REPO / ".gemini" / "skills"
    if not gemini_agents.is_dir():
        drift.append(".gemini/agents: missing directory")
    else:
        for p in (AI / "agents").glob("*.md"):
            dst = gemini_agents / p.name
            if mode == "symlink":
                if not dst.is_symlink() or not dst.exists():
                    drift.append(f".gemini/agents/{p.name}: missing or broken symlink")
            else:
                if not dst.exists() or not filecmp.cmp(p, dst, shallow=False):
                    drift.append(f".gemini/agents/{p.name}: missing or mismatched copy")

    if not gemini_skills.is_dir():
        drift.append(".gemini/skills: missing directory")
    else:
        for p in (AI / "skills").iterdir():
            if not p.is_dir() or p.name.startswith("."):
                continue
            dst = gemini_skills / p.name
            if mode == "symlink":
                if not dst.is_symlink() or not dst.exists():
                    drift.append(f".gemini/skills/{p.name}: missing or broken symlink")
            else:
                if not dst.is_dir():
                    drift.append(f".gemini/skills/{p.name}: missing copy directory")

    if drift:
        print(f"DRIFT DETECTED ({len(drift)} issues):", file=sys.stderr)
        for issue in drift:
            print(f"  - {issue}", file=sys.stderr)
        print("Run: python3 ai/skills/sync-framework/scripts/sync_framework.py", file=sys.stderr)
        return 1

    print(f"OK: All toolchains and mirrors are 100% in sync (mode={mode})")
    return 0


# ── Entrypoint ────────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--mode",
        choices=["auto", "symlink", "copy"],
        default="auto",
        help="Synchronization mode (default: auto)",
    )
    parser.add_argument("--copy", action="store_true", help="Alias for --mode=copy")
    parser.add_argument("--check", action="store_true", help="Check sync state and exit 1 on drift")
    parser.add_argument("--clean", action="store_true", help="Remove orphaned files in target directories")
    parser.add_argument("-v", "--verbose", action="store_true", help="Verbose output")
    args = parser.parse_args()

    target_mode = "copy" if args.copy else args.mode

    if args.check:
        expected = None if target_mode == "auto" else target_mode
        return run_check(expected_mode=expected, verbose=args.verbose)

    if target_mode == "auto":
        can_symlink = probe_symlink_capability(REPO)
        if can_symlink:
            target_mode = "symlink"
        else:
            print("Notice: Symlink creation not permitted or unsupported in this environment.")
            print("        Falling back to non-symlink COPY mode.")
            target_mode = "copy"

    return run_sync(mode=target_mode, clean=args.clean, verbose=args.verbose)


if __name__ == "__main__":
    sys.exit(main())
