def make_writable(path: Path) -> None:
    """Grant user write permission on a path if it exists."""
    if path.exists() or os.path.lexists(path):
        try:
            if path.is_dir() and not path.is_symlink():
                os.chmod(path, stat.S_IRWXU | stat.S_IRWXG | stat.S_IRWXO)
            else:
                os.chmod(path, stat.S_IWUSR | stat.S_IRUSR | stat.S_IWGRP | stat.S_IRGRP | stat.S_IROTH)
        except OSError:
            pass


def make_readonly(path: Path) -> None:
    """Grant read-only permission (0o444 on POSIX, S_IREAD on Windows)."""
    if path.exists():
        try:
            if path.is_dir() and not path.is_symlink():
                os.chmod(path, stat.S_IRUSR | stat.S_IXUSR | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)
            else:
                os.chmod(path, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
        except OSError:
            pass


def remove_path(path: Path) -> None:
    """Safely remove a file, symlink, or directory tree handling read-only bits."""
    if not (path.exists() or path.is_symlink() or os.path.lexists(path)):
        return
    if path.is_symlink() or path.is_file():
        make_writable(path)
        path.unlink(missing_ok=True)
    elif path.is_dir():
        def _ensure_dir_writable(p):
            try:
                os.chmod(p, stat.S_IRWXU | stat.S_IRWXG | stat.S_IRWXO)
            except OSError:
                pass

        _ensure_dir_writable(path)
        for root, dirs, files in os.walk(path):
            for d in dirs:
                _ensure_dir_writable(Path(root) / d)
            for f in files:
                try:
                    os.chmod(Path(root) / f, stat.S_IWUSR | stat.S_IRUSR)
                except OSError:
                    pass

        def _on_err(func, p, exc_info):
            try:
                _ensure_dir_writable(p)
                func(p)
            except OSError:
                pass

        if sys.version_info >= (3, 12):
            def _on_exc(func, p, exc):
                try:
                    _ensure_dir_writable(p)
                    func(p)
                except OSError:
                    pass
            shutil.rmtree(path, onexc=_on_exc)
        else:
            shutil.rmtree(path, onerror=_on_err)


def probe_symlink_capability(repo_dir: Path) -> bool:
    """Probe whether symlinks can be created in this environment."""
    probe_dir = repo_dir / ".gemini"
    probe_dir.mkdir(parents=True, exist_ok=True)
    probe_link = probe_dir / ".probe_symlink"
    try:
        if probe_link.is_symlink() or probe_link.exists():
            probe_link.unlink(missing_ok=True)
        os.symlink("settings.json", probe_link)
        resolves = probe_link.exists() or probe_link.is_symlink()
        probe_link.unlink(missing_ok=True)
        return bool(resolves)
    except (OSError, NotImplementedError):
        try:
            if probe_link.is_symlink() or probe_link.exists():
                probe_link.unlink(missing_ok=True)
        except OSError:
            pass
        return False


